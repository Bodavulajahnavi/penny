/**
 * Compiles the shared Tailwind CSS design system (src/app/globals.css) into the Django edition's
 * self-contained stylesheet, so the Python app needs no CDN or Node.js at runtime.
 *
 * Run after changing styles:  node scripts/build-python-css.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import tailwindcss from "@tailwindcss/postcss";
import postcss from "postcss";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "src/app/globals.css");
const output = path.join(root, "python/tracker/static/tracker/app.css");
const fontFace =
  '@font-face{font-family:"Inter Variable";font-style:normal;font-weight:100 900;font-display:swap;src:url("/static/tracker/inter.woff2") format("woff2")}';

const css = await readFile(source, "utf8");
const result = await postcss([tailwindcss({ base: root, optimize: { minify: true } })]).process(css, {
  from: source,
  to: output,
});
await writeFile(
  output,
  `/* Generated by scripts/build-python-css.mjs from src/app/globals.css. Do not edit by hand. */\n${fontFace}\n${result.css}\n`,
);
console.log(`Wrote ${path.relative(root, output)} (${(Buffer.byteLength(result.css) / 1024).toFixed(1)} KB)`);
